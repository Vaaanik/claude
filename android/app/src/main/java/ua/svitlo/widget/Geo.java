    /** Все места из справочника, упомянутые в тексте (text — после Threats.norm). */
    static List<Hit> find(String text) {
        List<Hit> out = new ArrayList<>();
        boolean[] taken = new boolean[text.length() + 1];
        for (Place pl : PLACES) {
            Matcher m = pl.pattern.matcher(text);
            while (m.find()) {
                // «Широка Дача» не должна ещё раз сработать как «Широке» и т.п.
                if (taken[m.start()]) continue;
                for (int i = m.start(); i < m.end(); i++) taken[i] = true;
                out.add(new Hit(pl, m.start()));
            }
        }
        out.sort((a, b) -> Integer.compare(a.at, b.at));
        return out;
    }

    static double distance(double lat1, double lon1, double lat2, double lon2) {
        double p1 = Math.toRadians(lat1), p2 = Math.toRadians(lat2);
        double dp = p2 - p1, dl = Math.toRadians(lon2 - lon1);
        double a = Math.sin(dp / 2) * Math.sin(dp / 2)
                + Math.cos(p1) * Math.cos(p2) * Math.sin(dl / 2) * Math.sin(dl / 2);
        return 2 * 6371 * Math.asin(Math.sqrt(a));
    }

    /** С какой стороны от города находится точка. */
    static String side(double lat1, double lon1, double lat2, double lon2) {
        double y = Math.sin(Math.toRadians(lon2 - lon1)) * Math.cos(Math.toRadians(lat2));
        double x = Math.cos(Math.toRadians(lat1)) * Math.sin(Math.toRadians(lat2))
                - Math.sin(Math.toRadians(lat1)) * Math.cos(Math.toRadians(lat2))
                * Math.cos(Math.toRadians(lon2 - lon1));
        double deg = (Math.toDegrees(Math.atan2(y, x)) + 360) % 360;
        String[] names = {"к северу", "к северо-востоку", "к востоку", "к юго-востоку",
                "к югу", "к юго-западу", "к западу", "к северо-западу"};
        return names[(int) Math.round(deg / 45) % 8];
    }

